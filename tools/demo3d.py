#!/usr/bin/env python3
"""Writes the 3-D demo pages: ``demo/`` (pt-BR) and ``en/demo/`` (English).

    python3 tools/demo3d.py [--pinneapple ../PINNeAPPle]

The page is not rendered by ``build.py``: it is generated by the library
(``pp.viz.cinematic_page``), which writes ``index.html``, ``scene.glb``, ``scene.json`` and the vendored three.js
into each folder. ``build.py`` only gives the page its metadata and its place in the navigation and the sitemap, so
run this script once and ``build.py`` whenever the shell changes.

The scene is the A320-class airliner from ``pinneapple_design.aero`` carrying the pressure coefficient of the stored
OpenFOAM run of ``apps/aero_optimizer`` -- the same numbers the aero report shows, not a decorative field.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

CSS = (
    'body { font-family: "Archivo", system-ui, sans-serif; }\n'
    '  h1, h2 { font-family: "Archivo", system-ui, sans-serif; }\n'
    '  .kicker, #hud, .bar { font-family: "JetBrains Mono", ui-monospace, monospace; }\n'
    '  :root { --accent: #3dd6c4; }'
)

SECTIONS = {
    "pt": [
        {"kicker": "PINNeAPPle Labs", "title": "O que o ar faz com uma asa",
         "body": "Uma aeronave classe A320, com o coeficiente de pressão de uma rodada de OpenFOAM sobre a pele."},
        {"kicker": "O resultado", "title": "Cp na pele",
         "body": "Azul onde o escoamento acelera, vermelho onde ele para. A mesma escala do relatório."},
        {"kicker": "A verificação", "title": "O número sai com o erro declarado",
         "body": "Cada estudo é checado contra referência antes de virar relatório."},
        {"kicker": "O Studio", "title": "Da geometria ao relatório",
         "body": "Geometria, malha, solver e a página que o cliente abre no navegador."},
    ],
    "en": [
        {"kicker": "PINNeAPPle Labs", "title": "What the air does to a wing",
         "body": "An A320-class aircraft with the pressure coefficient of an OpenFOAM run on its skin."},
        {"kicker": "The result", "title": "Cp on the skin",
         "body": "Blue where the flow speeds up, red where it stops. The same scale as the report."},
        {"kicker": "Verification", "title": "The number ships with its declared error",
         "body": "Every study is checked against a reference before it becomes a report."},
        {"kicker": "The Studio", "title": "From geometry to report",
         "body": "Geometry, mesh, solver and the page the client opens in a browser."},
    ],
}

TITLES = {"pt": "A320 em cruzeiro", "en": "A320 in cruise"}
LABELS = {"pt": "Coeficiente de pressão Cp (OpenFOAM)", "en": "Pressure coefficient Cp (OpenFOAM)"}

HEAD = {
    "pt": ('<link rel="stylesheet" href="{css}fonts.css" />\n'
           '<link rel="icon" href="{css}favicon.svg" type="image/svg+xml" />\n'
           '<meta name="description" content="Uma aeronave classe A320 com o coeficiente de pressão de uma rodada de '
           'OpenFOAM, em 3-D no navegador." />'),
    "en": ('<link rel="stylesheet" href="{css}fonts.css" />\n'
           '<link rel="icon" href="{css}favicon.svg" type="image/svg+xml" />\n'
           '<meta name="description" content="An A320-class aircraft with the pressure coefficient of an OpenFOAM '
           'run, in 3-D in the browser." />'),
}

# folder, <html lang>, prefix to the site root (fonts, icon), back link, geometry URL
TARGETS = {"pt": ("demo", "pt-BR", "../", "../", None),
           "en": ("en/demo", "en", "../../", "../../", "../../demo/scene.glb")}


def build_scene(lib: Path):
    """The airliner with its OpenFOAM Cp, as ``examples/studio/03_airliner_with_cfd.py`` builds it."""
    sys.path.insert(0, str(lib))
    import numpy as np
    import pinneapple as pp
    from pinneapple_design.aero.airliner3d import airliner_from, baseline_x_al

    model = lib / "apps" / "aero_optimizer" / "model"
    x = baseline_x_al()
    parts = airliner_from(x).build("high")
    scene = pp.viz.Scene.from_parts(parts, title=TITLES["pt"])
    designs = json.loads((model / "verification3d.json").read_text())["designs"]
    record = next(d for d in designs if np.allclose(d["x"], x, atol=1e-4))
    z = np.load(model / "cfd3d" / f"{record['id']}.npz")
    aero = [p.name for p in parts if p.aero]
    scene.map_field("cp", z["xyz"], z["cp"], mirror_y=True, surfaces=aero, label=LABELS["pt"])
    return pp, scene


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--pinneapple", default=str(ROOT.parent / "PINNeAPPle"), help="the library checkout")
    args = ap.parse_args()

    lib = Path(args.pinneapple).resolve()
    if not (lib / "pinneapple").is_dir():
        print(f"not a PINNeAPPle checkout: {lib} (pass --pinneapple)", file=sys.stderr)
        return 2

    pp, scene = build_scene(lib)
    for lang, (folder, html_lang, css, home, scene_url) in TARGETS.items():
        out = ROOT / folder
        scene.labels["cp"] = LABELS[lang]
        page = pp.viz.cinematic_page(
            scene, str(out), field="cp", title=TITLES[lang], sections=SECTIONS[lang],
            css=CSS, head=HEAD[lang].format(css=css), lang=html_lang, home=home, scene_url=scene_url)
        print("wrote", os.path.relpath(page, ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
